// server/db.js — the single readonly handle onto the datagenerator2 dataset.
//
// The dataset is generated elsewhere and consumed in place (docs/plan.md §1, §3); nothing
// here ever writes. Every query goes through measured(), which times it and — in dev —
// captures its EXPLAIN QUERY PLAN so the harness request log can flag a missing index
// while the UI is being built rather than later (§7.4).

import { Database } from "bun:sqlite";
import { existsSync, readFileSync, statSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

export const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");

// Where the dataset lives, in order of preference. The dataset is generated by
// datagenerator2 and read in place — there is never a reason to copy it here, and a copy is
// worse than no copy because a stale one is indistinguishable from a fresh one.
//
//   1. MERCHANT_DB_PATH            explicit override, wins over everything
//   2. datagenerator2's own config it writes wherever `sqlite_path` says, so read that
//                                  rather than assuming, or changing the setting there
//                                  silently points this project at a stale file
//   3. the conventional location    ../datagenerator2/out/datagenerator.db
//   4. ./data/datagenerator.db      a local copy, if someone made one anyway
const generatorDir = resolve(
  process.env.MERCHANT_GENERATOR_DIR ?? resolve(projectRoot, "../datagenerator2"),
);

// datagenerator.env is `key = value` lines. Only one key is wanted and a malformed file
// should degrade to the convention rather than stop the server.
function configuredGeneratorPath() {
  try {
    const envFile = resolve(generatorDir, "datagenerator.env");
    if (!existsSync(envFile)) return null;
    for (const line of readFileSync(envFile, "utf8").split("\n")) {
      const m = /^\s*sqlite_path\s*=\s*(.+?)\s*$/.exec(line);
      if (m && m[1] && m[1] !== ":memory:") return resolve(generatorDir, m[1]);
    }
  } catch {}
  return null;
}

function resolveDbPath() {
  const candidates = [
    process.env.MERCHANT_DB_PATH && {
      path: resolve(process.env.MERCHANT_DB_PATH),
      source: "MERCHANT_DB_PATH",
    },
    (() => {
      const p = configuredGeneratorPath();
      return p && { path: p, source: "datagenerator2 sqlite_path" };
    })(),
    { path: resolve(generatorDir, "out/datagenerator.db"), source: "conventional location" },
    { path: resolve(projectRoot, "data/datagenerator.db"), source: "local copy in ./data" },
  ].filter(Boolean);

  const found = candidates.find((c) => existsSync(c.path));
  // An explicit override that does not exist is an error, not something to fall past.
  if (process.env.MERCHANT_DB_PATH && found?.source !== "MERCHANT_DB_PATH") {
    throw new Error(
      `MERCHANT_DB_PATH is set to ${resolve(process.env.MERCHANT_DB_PATH)} but no file is there.`,
    );
  }
  if (!found) {
    throw new Error(
      `No dataset found. Looked in:\n` +
        candidates.map((c) => `    ${c.path}   (${c.source})`).join("\n") +
        `\n  Generate it with \`bun run generate\` in ${generatorDir}, or set MERCHANT_DB_PATH.`,
    );
  }
  return found;
}

const resolved = resolveDbPath();
export const dbPath = resolved.path;
export const dbSource = resolved.source;
// Surfaced at startup and in /api/harness/dataset: a dataset generated days ago after a
// schema change is the likeliest reason for something inexplicable.
export const dbGeneratedAt = statSync(dbPath).mtime;

// A copy in ./data is only read when nothing else is present, so one sitting there while the
// generated file is being read is dead weight — 140 MB that is either already stale or one
// regeneration away from it, and indistinguishable from the live dataset when you look.
// Flagged whether or not it is currently behind: an identical copy is the dangerous case,
// because it looks fine right up until it silently isn't.
const localCopy = resolve(projectRoot, "data/datagenerator.db");
export const unusedLocalCopy =
  dbPath !== localCopy && existsSync(localCopy)
    ? {
        path: localCopy,
        stale: statSync(localCopy).mtime.getTime() !== dbGeneratedAt.getTime(),
      }
    : null;

export const isDev = process.env.NODE_ENV !== "production";


export const db = new Database(dbPath, { readonly: true });

// Plans are only interesting during development, and EXPLAIN costs a second prepare.
function planFor(sql, params) {
  try {
    return db
      .query(`explain query plan ${sql}`)
      .all(...params)
      .map((r) => r.detail);
  } catch {
    return [];
  }
}

// A plan line containing either of these means SQLite is doing work an index could avoid.
const SLOW_MARKERS = [/\bSCAN\b/, /TEMP B-TREE/];

// Scanning is only a problem when it costs something. A full scan of the 28-row branch
// table takes 0.4 ms and wants no index; the same plan over aged_debt's 1.19M rows takes
// 38 ms and very much does. Warning on the plan alone would cry wolf on every small
// lookup and train us to ignore it, so the time has to agree.
export const WARN_MS = Number(process.env.MERCHANT_WARN_MS ?? 5);

export function planWarnings(plan, tookMs) {
  if (tookMs < WARN_MS) return [];
  return plan.filter((line) => SLOW_MARKERS.some((re) => re.test(line)));
}

// Run a named query and return rows plus the timing/plan metadata the harness displays.
export function measured(name, sql, params = []) {
  const started = performance.now();
  const rows = db.query(sql).all(...params);
  const tookMs = Number((performance.now() - started).toFixed(2));
  const plan = isDev ? planFor(sql, params) : [];
  return { query: name, rows, total: rows.length, tookMs, plan, warnings: planWarnings(plan, tookMs) };
}

// Single-row variant; returns null rather than undefined so JSON stays predictable.
export function measuredOne(name, sql, params = []) {
  const result = measured(name, sql, params);
  return { ...result, row: result.rows[0] ?? null };
}
